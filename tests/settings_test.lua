-- Saved settings: defaults, and what a player types for the margin.
local ns, test, eq = ...
local Settings = ns.Settings

test("a first load gets the defaults", function()
  local s = Settings.Normalize(nil)
  eq(s.margin, 0.20)
  eq(s.hasEnchanterAlt, true)
  eq(type(s.keep), "table")
  eq(type(s.log), "table")
  eq(s.debugMode, false)
  eq(s.buttonOnAll, false)
  eq(type(s.prices), "table")
  eq(s.autoScan, true)
  eq(s.showResults, true, "the line after each disenchant is on")
  eq(s.minimap.hide, false)
  eq(type(s.minimap.angle), "number")
end)

test("a moved or hidden minimap button stays that way", function()
  local s = Settings.Normalize({ minimap = { angle = 90, hide = true }, buttonOnAll = true })
  eq(s.minimap.angle, 90)
  eq(s.minimap.hide, true)
  eq(s.buttonOnAll, true)
end)

test("the minimap button sits on a circle around the minimap", function()
  local x, y = Settings.MinimapOffset(0, 80)
  eq(math.floor(x + 0.5), 80); eq(math.floor(y + 0.5), 0)
  x, y = Settings.MinimapOffset(90, 80)
  eq(math.floor(x + 0.5), 0); eq(math.floor(y + 0.5), 80)
  x, y = Settings.MinimapOffset(180, 80)
  eq(math.floor(x + 0.5), -80)
end)

test("dragging turns the cursor position into an angle", function()
  eq(Settings.MinimapAngle(10, 0), 0)
  eq(Settings.MinimapAngle(0, 10), 90)
  eq(Settings.MinimapAngle(-10, 0), 180)
  eq(Settings.MinimapAngle(0, -10), 270)
end)

test("stored choices are kept, including a switched-off enchanter alt", function()
  local stored = { margin = 0.35, hasEnchanterAlt = false, keep = { [123] = true } }
  local s = Settings.Normalize(stored)
  eq(s, stored, "the same table, so saving keeps working")
  eq(s.margin, 0.35)
  eq(s.hasEnchanterAlt, false)
  eq(s.keep[123], true)
end)

test("a broken stored value falls back to its default", function()
  local s = Settings.Normalize({ margin = "lots", hasEnchanterAlt = "yes", keep = 5 })
  eq(s.margin, 0.20)
  eq(s.hasEnchanterAlt, true)
  eq(type(s.keep), "table")
  eq(Settings.Normalize({ margin = -1 }).margin, 0.20)
  eq(Settings.Normalize({ margin = 7 }).margin, 0.20)
end)

test("a saved window size and position is kept", function()
  local s = Settings.Normalize({ window = { width = 700, height = 650, point = "TOPLEFT", x = 100, y = -80 } })
  eq(s.window.width, 700)
  eq(s.window.point, "TOPLEFT")
end)

test("a broken window entry is dropped, so the default is used", function()
  eq(Settings.Normalize({ window = "big" }).window, nil)
  eq(Settings.Normalize({ window = { width = "wide", height = 600 } }).window, nil)
  eq(Settings.Normalize({}).window, nil)
end)

test("the margin is typed as a percentage", function()
  eq(Settings.ParseMargin("25"), 0.25)
  eq(Settings.ParseMargin(" 10% "), 0.10)
  eq(Settings.ParseMargin("0"), 0)
  eq(Settings.ParseMargin("12.5"), 0.125)
end)

test("a margin that is not a percentage between 0 and 100 is refused", function()
  eq(Settings.ParseMargin("abc"), nil)
  eq(Settings.ParseMargin(""), nil)
  eq(Settings.ParseMargin("-5"), nil)
  eq(Settings.ParseMargin("150"), nil)
end)
